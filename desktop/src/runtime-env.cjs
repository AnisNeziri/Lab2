function sanitizeInheritedEnvironment(source) {
  return Object.fromEntries(Object.entries(source).filter(([key]) =>
    !/^(DB_|MYSQL_)/i.test(key) &&
    !/^(APP_KEY|JWT_SECRET|AIMS_DESKTOP_RECOVERY_PASSWORD|REDIS_PASSWORD|AISSTREAM_API_KEY|VESSELAPI_API_KEY|REVERB_APP_SECRET|STRIPE_SECRET|MAIL_PASSWORD|AIMS_DOCUMENT_ROOT|AIMS_BACKUP_ROOT|AIMS_BACKUP_PASSPHRASE_FILE|AIMS_BACKUP_SCHEDULE|APP_CONFIG_CACHE|AIMS_LICENSE_PUBLIC_KEY_FILE|AIMS_UPDATE_PUBLIC_KEY_FILE|AIMS_IDENTITY_RECOVERY_KEY_HASH|AIMS_MCP_TOKEN|AIMS_PASSKEY_RP_ID|AIMS_PASSKEY_ORIGINS|AIMS_DESKTOP_LICENSE_FILE|AIMS_DESKTOP_LICENSE_PUBLIC_KEY|AIMS_DESKTOP_LICENSE_MACHINE_ID)$/i.test(key)
  ))
}

module.exports = { sanitizeInheritedEnvironment }
