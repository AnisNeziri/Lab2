export async function downloadAccountingCsv(report, params={}) {
  const response = await authenticatedFetch(buildApiUrl(`/accounting/exports/${report}`, params))
  if (!response.ok) await parseApiResponse(response, 'Unable to export financial records.')
  const url=URL.createObjectURL(await response.blob()), link=document.createElement('a')
  link.href=url; link.download=`aims-${report}-${params.to || 'current'}.csv`; link.click(); setTimeout(()=>URL.revokeObjectURL(url),1000)
  return {exported:true}
}
