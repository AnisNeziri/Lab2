import { test, expect } from '@playwright/test'
import { login } from '../helpers/auth.mjs'

test('@smoke owner sees honest pilot readiness, saves a draft and captures a review', async ({page}) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await login(page);await page.goto('/pilot')
  await expect(page.getByRole('heading',{name:'Company pilot',exact:true})).toBeVisible()
  await expect(page.getByText('Test or demo data detected',{exact:true})).toBeVisible()
  await expect(page.getByText('Pilot completion and primary operational approval remain unverified.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Rollout plan',exact:true}).click()
  await page.getByLabel('Daily tasks and AIMS workflows',{exact:true}).fill('Review stock and daily reconciliation')
  await page.getByLabel('Operational cutover date',{exact:true}).fill('2026-10-05')
  await page.getByRole('button',{name:'Save rollout plan',exact:true}).click()
  await expect(page.getByRole('button',{name:'Save rollout plan',exact:true})).toBeEnabled()
  const token=await page.evaluate(()=>localStorage.getItem('api_token'))
  const response=await page.request.get('/api/pilot',{headers:{Authorization:`Bearer ${token}`}})
  expect(response.ok()).toBeTruthy();expect((await response.json()).readiness.profile.status).toBe('draft')
  await page.getByRole('button',{name:'Reviews',exact:true}).click()
  await page.getByRole('button',{name:'Capture snapshot',exact:true}).click()
  await expect(page.getByRole('button',{name:'Open',exact:true}).first()).toBeVisible()
  await page.getByRole('button',{name:'Open',exact:true}).first().click()
  await expect(page.getByRole('dialog')).toContainText('Primary operational approval: pending owner exit review.')
  await page.keyboard.press('Escape')
  await page.evaluate(async()=>{window.__aimsCertification.useSettingsStore.getState().applyPreferences({language:'sq',theme:'dark'})})
  await expect(page.getByRole('heading',{name:'Piloti i kompanisë',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Gatishmëria e të dhënave',exact:true}).click()
  await expect(page.getByText('U zbuluan të dhëna testimi ose demo',{exact:true})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBeTruthy()
  expect(errors).toEqual([])
})

test('@smoke quick feedback captures the page and redacts sensitive free text', async ({page}) => {
  await login(page);await page.goto('/products?search=private-search-token')
  await page.getByRole('button',{name:'Report a problem',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Report a problem',exact:true})
  await dialog.getByLabel('What happened? (optional)',{exact:true}).fill('Slow list password=secret-password customer@example.com')
  await dialog.getByRole('button',{name:'Send report',exact:true}).click()
  await expect(dialog).toContainText('Report saved for your company administrator.')
  await page.keyboard.press('Escape');await page.goto('/pilot')
  await page.getByRole('button',{name:'Feedback',exact:true}).click()
  await expect(page.getByText('Slow list password=[redacted] [email]',{exact:true})).toBeVisible()
  await expect(page.locator('.pilot-page')).not.toContainText('private-search-token')
  await expect(page.locator('.pilot-page')).not.toContainText('secret-password')
})

test('pilot CSV preflight reports missing fields without importing products', async ({page}) => {
  await login(page);await page.goto('/pilot')
  await page.getByRole('button',{name:'Import preflight',exact:true}).click()
  await page.getByLabel('CSV',{exact:true}).setInputFiles({name:'pilot-products.csv',mimeType:'text/csv',buffer:Buffer.from('sku,name,unit\nPR3-NEW-1,Review only,pcs\nPR3-NEW-2,Missing unit,\n')})
  await page.getByRole('button',{name:'Review file',exact:true}).click()
  await expect(page.getByText('Imported rows: 0',{exact:true})).toBeVisible()
  await expect(page.getByText('SHA-256:',{exact:false})).toBeVisible()
})

test('staff can record a routine trial while the owner dashboard stays protected', async ({page}) => {
  await login(page,'staff');await page.goto('/pilot-evidence')
  await page.getByLabel('Trial',{exact:true}).selectOption('workflow_timing')
  await page.getByLabel('Check 1',{exact:true}).fill('Stock lookup observed with warehouse staff')
  await page.getByRole('button',{name:'Save observation',exact:true}).click()
  await expect(page.getByText('Observation saved. A different authorized reviewer must confirm it.',{exact:true})).toBeVisible()
  await expect(page.getByText('Stock lookup observed with warehouse staff: Not tested',{exact:true})).toBeVisible()
  const token=await page.evaluate(()=>localStorage.getItem('api_token'))
  const result=await page.request.get('/api/pilot',{headers:{Authorization:`Bearer ${token}`}})
  expect(result.status()).toBe(403)
  await page.goto('/pilot');await expect(page).toHaveURL(/\/dashboard$/)
})
