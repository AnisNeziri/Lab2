import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

test('Action Center → claim → explain → explicitly confirmed procurement draft → company pause', async ({ page }) => {
  test.setTimeout(120000)
  const f=JSON.parse(readFileSync(fileURLToPath(new URL('../../../output/dc6-fixture.json',import.meta.url)),'utf8'))
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/login')
  await page.getByLabel(/Email address|Adresa e emailit/).fill(f.email)
  await page.getByLabel(/^(Password|Fjalëkalimi)$/).fill('dc6-local-test-secret')
  await page.getByRole('button',{name:/Enter workspace|Hyr në sistem/}).click()
  await expect(page).toHaveURL(/dashboard$/)
  await page.evaluate(()=>window.__aimsCertification.useSettingsStore.getState().applyPreferences({language:'en',theme:'light'}))
  const inboxLoaded=page.waitForResponse(r=>r.url().includes('/api/action-center?')&&r.request().method()==='GET',{timeout:30000})
  await page.goto('/action-center?view=team&team=purchasing')
  expect((await inboxLoaded).status()).toBe(200)
  const task=page.locator(`[data-task-id="${f.task}"]`)
  await expect(task).toContainText('Review Milano replenishment')
  await task.getByRole('button',{name:'Claim task',exact:true}).click()
  await expect(task).toContainText('DC6 Purchasing Reviewer')
  await task.getByRole('button',{name:'Review task & evidence',exact:true}).click()
  let review=page.getByRole('dialog',{name:'Task review & next action'})
  await expect(review).toContainText('1,450')
  await review.getByRole('button',{name:'Ask AIMS about this',exact:true}).click()
  const assistant=page.getByRole('complementary',{name:'AIMS Assistant'})
  await expect(assistant).toContainText('The task preserves its trigger evidence and current state.')
  await assistant.getByRole('button',{name:'Close assistant',exact:true}).click()
  await task.getByRole('button',{name:'Review task & evidence',exact:true}).click()
  review=page.getByRole('dialog',{name:'Task review & next action'})
  await review.getByRole('button',{name:'Prepare purchase request',exact:true}).click()
  const confirmation=review.getByRole('region',{name:'Confirm purchase request draft'})
  await expect(confirmation).toContainText('DC6 Textiles')
  await confirmation.getByRole('button',{name:'Create draft purchase request',exact:true}).click()
  await expect(review.getByRole('status')).toContainText('Purchase request draft created.')
  await expect(review.getByRole('link',{name:/Review purchase request/})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:fileURLToPath(new URL('../../../output/dc6-task-mobile.png',import.meta.url)),fullPage:true})
  await review.getByRole('button',{name:'Close',exact:true}).click()
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('/automation-studio')
  await page.getByText('Automation health and pause controls',{exact:true}).click()
  const health=page.getByRole('region',{name:'Automation health',exact:true})
  await health.getByRole('button',{name:'Company pause controls',exact:true}).click()
  await health.getByRole('checkbox',{name:'Pause all company automation',exact:true}).check()
  await health.getByRole('textbox',{name:'Reason',exact:true}).fill('Synthetic controlled pilot pause')
  await health.getByRole('button',{name:'Apply automation controls',exact:true}).click()
  await expect(health.getByRole('status')).toContainText('Company automation paused')
  await page.screenshot({path:fileURLToPath(new URL('../../../output/dc6-automation-health.png',import.meta.url)),fullPage:true})
  await page.goto('/action-center?view=team&team=purchasing')
  await expect(page.getByRole('status').filter({hasText:'Automation is paused.'})).toBeVisible()
  // Pausing orchestration does not lock the manual stock workspace.
  const stockLoaded=page.waitForResponse(r=>r.url().includes('/api/inventory/control-center')&&r.request().method()==='GET',{timeout:30000})
  await page.goto('/warehouse-operations?tab=control')
  expect((await stockLoaded).status()).toBe(200)
  await expect(page.getByRole('region',{name:'Inventory Control Center',exact:true})).toContainText('Milano 04')
  expect(errors).toEqual([])
})
