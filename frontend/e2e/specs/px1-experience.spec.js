import path from 'node:path'
import {fileURLToPath} from 'node:url'
const output=fileURLToPath(new URL('../../../output/',import.meta.url))
const fixture=()=>JSON.parse(readFileSync(path.join(output,'px1-fixture.json'),'utf8'))
async function login(page,role='owner') {
  await page.goto('/login')
  await page.getByLabel(/Email address|Adresa e emailit/).fill(`px1-${role}@e2e.example`)
  await page.getByLabel(/^(Password|Fjalëkalimi)$/).fill('px1-local-test-secret')
  await page.getByRole('button',{name:/Enter workspace|Hyr në sistem/}).click()
  await expect(page).toHaveURL(/dashboard$/)
  await expect(page.getByRole('heading',{level:1})).toBeVisible()
}
async function mode(page,language='en',theme='light') {
  await page.evaluate(({language,theme})=>window.__aimsCertification.useSettingsStore.getState().applyPreferences({language,theme}),{language,theme})
}
async function noPageOverflow(page) {
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2)).toBe(true)
}
async function api(page,route) {
  return page.evaluate(async route=>{
    const r=await fetch('/api'+route,{headers:{Accept:'application/json',Authorization:'Bearer '+localStorage.getItem('api_token')}})
    return {status:r.status,data:await r.json()}
  },route)
}

